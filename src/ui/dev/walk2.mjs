// Dev-only: second pass (watchlist detail, settings, empty deck, join-with-code error, onboarding re-run).
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const out = process.argv[2] ?? 'shots';
mkdirSync(out, { recursive: true });
const URL = 'http://localhost:5173/what-to-watch/?catalog=fixture&sync=memory';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` });
const tid = (id) => page.getByTestId(id);
await page.goto(URL);
// join error
await tid('person-BG').click();
await tid('have-code').click();
await tid('code-input').fill('abc123');
await tid('code-submit').click();
await tid('pair-error').waitFor();
await shot('30-join-error');
console.log('join error:', await tid('pair-error').innerText());
await tid('code-back').click();
await tid('start-household').click();
await tid('onboard-skip').click();
await tid('ask').waitFor();
// empty deck: time 20 + rewatch + background + genre horror
await tid('ask-viewing-background').click();
await tid('ask-time-20').click();
await tid('ask-novelty-rewatch').click();
await tid('ask-genre-western').click();
await tid('ask-submit').click();
for (let i = 0; i < 60 && !(await tid('empty-deck').count()); i++) { await tid('action-not-tonight').click(); await page.waitForTimeout(300); }
await tid('empty-deck').waitFor();
await shot('31-empty');
await tid('empty-back').click();
// save to watchlist then detail
await tid('ask-novelty-either').click();
await tid('ask-viewing-focused').click();
await tid('ask-genre-any').click();
await tid('ask-time-120').click();
await tid('ask-submit').click();
await tid('card').waitFor();
await tid('action-save').click();
await tid('save-option-ours').click();
await page.waitForTimeout(500);
await tid('action-save').click();
await tid('save-option-BG').count().then((c) => console.log('BG option while asking self:', c));
await tid('save-option-BG').count() || await tid('save-option-BG').count();
await page.keyboard.press('Escape');
await page.mouse.click(200, 100);
await tid('tab-watchlist').click();
await tid('watchlist-tab-ours').click();
await shot('32-watchlist');
await page.getByTestId('watchlist-row').first().click();
await page.waitForTimeout(400);
await shot('33-watchlist-detail');
await tid('watchlist-close').click();
// settings
await tid('tab-us').click();
await tid('us-seg-settings').click();
await shot('34-settings');
await page.getByTestId('about').scrollIntoViewIfNeeded();
await shot('35-about');
await tid('plan-hulu-none').click();
await page.waitForTimeout(100);
console.log('hulu none selected:', await tid('plan-hulu-none').getAttribute('data-selected'));
// profile insights
await tid('us-seg-HG').click();
await page.getByTestId('insight-line').first().scrollIntoViewIfNeeded();
await shot('36-insights');
const first = page.getByTestId('insight-more').first();
await first.click();
await page.waitForTimeout(150);
console.log('insight correction:', await page.getByTestId('insight-line').first().getAttribute('data-correction'));
await tid('profile-redo-onboarding').scrollIntoViewIfNeeded();
await tid('profile-redo-onboarding').click();
await tid('onboarding').waitFor();
await tid('onboard-skip').click();
await tid('us').waitFor();
console.log('ERRORS', errors);
await browser.close();
